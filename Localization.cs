    public static string Language { get; private set; } = "en";

    public static bool IsSupported(string? language) =>
        language is not null && Table.ContainsKey(Normalize(language));

    public static string Normalize(string? language)
    {
        if (string.IsNullOrWhiteSpace(language)) return "en";
        var value = language.Trim().ToLowerInvariant();
        if (value.Length > 2) value = value[..2];
        return Table.ContainsKey(value) ? value : "en";
    }

    public static void SetLanguage(string? language) => Language = Normalize(language);

    public static string T(string key)
    {
        if (Table[Language].TryGetValue(key, out var value)) return value;
        return Table["en"].TryGetValue(key, out var fallback) ? fallback : key;
    }

    public static string F(string key, params object[] args) => string.Format(T(key), args);
